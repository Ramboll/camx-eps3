c
      subroutine clslbs()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the LBASE program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iolbase.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORINP)
c
      close(IORLNK)
c
      close(IOWMSG)
c
      close(IOWMBR)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
