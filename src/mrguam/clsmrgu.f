C**** CLSMRGU.F 
c
      subroutine clsmrgu( )
c
c-----------------------------------------------------------------------
c
c    Close files
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iomrguam.inc'
c
c-----------------------------------------------------------------------
c    Argument Declarations:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Local Variables:
c-----------------------------------------------------------------------
c
      integer*4 iounit, i
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
      close(unit=IORINP)
c
      close(unit=IOWMSG)
c
      close(unit=IOWUAM)
c
c   --- generate unit numbers ---
c
      iounit=MXUNIT
      do i=1,iflcnt
          iounit=iounit+1
          close(unit=iounit)
      enddo
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
      return
      end
