C**** CLSEVT.F 
c
      subroutine clsevt()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the EMSCVT program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'ioemscvt.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORUIN)
c
      close(IORCDB)
c
      close(IORPRW)
c
      close(IORXRF)
c
      close(IORSPL)
c
      close(IOWMSG)
c
      close(IOWXRF)
c
      close(IOWSPL)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
