C**** CLSTMP.F 
c
      subroutine clstmp()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the TMPRL program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iotmprl.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORINP)
c
      close(IORMBR)
c
      close(IORXRF)
c
      close(IORPRF)
c
      close(IOWMSG)
c
      close(IOWMBR)
c
      close(IOWERR)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
