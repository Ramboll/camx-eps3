C*** CLSPRS.F 
c
      subroutine clsprs()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the PRESHP program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iopreshp.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORINP)
c
      close(IORSHP)
c
      close(IOWMSG)
c
      close(IOWMBR)
c
      close(IOWSTK)
c
      close(IOWERR)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
