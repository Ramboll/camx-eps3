C**** INIT_HASH_MSGTOT.F
c
      subroutine init_hash_msgtot(  )
c
c-----------------------------------------------------------------------
c
c   Description:
c
c     This routine initializes all of the hash function index arrays
c     for the msgtot lookups to missing value.
c
c   Arguments:
c     Inputs:
c     Outputs:
c
c-----------------------------------------------------------------------
c   LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Argument declaration:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Include files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'hash.inc'
      include 'msgtot.inc'
c
c-----------------------------------------------------------------------
c   Local variables:
c-----------------------------------------------------------------------
c
      integer*4    i
c
c-----------------------------------------------------------------------
c   Data statements:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Entry point:
c-----------------------------------------------------------------------
c
      do i=1,MXHASH_PAIR
         idxhsh_first_pair(i) = IMISS
      enddo
c
      do i=1,MXHASH_ASC
         idxhsh_first_asc(i) = IMISS
      enddo
c
      do i=1,MXASC
         idxhsh_msgtot_next_asc(i) = IMISS
      enddo
c
      do i=1,MXFCD
         idxhsh_msgtot_next_pair(i) = IMISS
      enddo
c
c-----------------------------------------------------------------------
c   Format statements:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Return point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
