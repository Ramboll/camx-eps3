C***** CLSPST.F 
c
      subroutine clspst()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the PSTPNT program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iopstpnt.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORINP)
c
      close(IORMBR)
c
      close(IOWMSG)
c
      close(IOWEMS)
c
      close(IOWHDR)
c
      close(IOWERR)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
