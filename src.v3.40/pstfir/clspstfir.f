C*** CLSPSTFIR.F
c
      subroutine clspstfir()
c
c-----------------------------------------------------------------------
c
c    Closes all files used by the PSTFIR program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iopstfir.inc'
      include 'netcdf.inc'
c
c-----------------------------------------------------------------------
c    Local variables:
c-----------------------------------------------------------------------
c
      integer*4 ierr
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORINP)
c
      close(IORMBR)
c
      close(IOWMSG)
c
      close(IOWELV)
c
      close(IOWHDR)
c
      close(IOWSRF)
c
      close(IOWERR)
c
      if( l3demiss ) ierr = nf_close(ncf_iowemis)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
