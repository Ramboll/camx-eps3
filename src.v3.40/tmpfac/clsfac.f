c
      subroutine clsfac()
c
c-----------------------------------------------------------------------
c
c    closes all files used by the TMPFAC program
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
      include 'param.inc'
      include 'iotmpfac.inc'
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
c   --- close files ---
c
      close(IORXRF)
c
      close(IORPRF)
c
      close(IORAFS)
c
      close(IOWMSG)
c
      close(IOWXRF)
c
      close(IOWPRF)
c
      goto 9999
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
