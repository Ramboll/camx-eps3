c**** SORT2.F
c
      subroutine sort2( v1, v2, vmin, vmax )
c
c-----------------------------------------------------------------------
c
c    This subroutine sorts two numbers
c
c     code by Brett Larkin, Computers & Geoscience (1988), v14, pp1-14
c     adapted for EPS3 by ENVIRON International Corp, 2009
c
c   Argument Declaration:
! input:     
c   Inputs:
c     vl   R  first of the two numbers to be sorted
c     v2   R  second of the two numbers to be sorted
c   Outputs:
c     vmin   R  the minimum of the two numbers
c     vmax   R  the maximum of the two numbers
c
c-----------------------------------------------------------------------
c    LOG:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Include Files:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c    Argument decelarations:
c-----------------------------------------------------------------------
c
      real*4 v1
      real*4 v2 
      real*4 vmin 
      real*4 vmax
c
c-----------------------------------------------------------------------
c    External Functions:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Local Variables:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Data statements:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Entry Point:
c-----------------------------------------------------------------------
c
      if(v1 .LE. v2) then
           vmin = v1
           vmax = v2
      else
           vmin = v2
           vmax = v1
      endif
      goto 9999
c
c-----------------------------------------------------------------------
c   Warning messages:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Error Messages:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Format Statements:
c-----------------------------------------------------------------------
c
c-----------------------------------------------------------------------
c   Return Point:
c-----------------------------------------------------------------------
c
 9999 continue
      return
      end
